import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import puppeteer from 'puppeteer-core';
const ROOT=new URL('..',import.meta.url).pathname; const DIST=join(ROOT,'dist'); const OUT=join(ROOT,'shots'); const PORT=4422;
const MIME={'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.png':'image/png','.webmanifest':'application/manifest+json'};
const server=createServer(async(req,res)=>{ let p=normalize(decodeURIComponent(new URL(req.url,'http://x').pathname)); if(p==='/')p='/index.html';
  try{const b=await readFile(join(DIST,p));res.writeHead(200,{'Content-Type':MIME[extname(p)]??'application/octet-stream'});res.end(b);}catch{res.writeHead(404);res.end();}});
await new Promise(r=>server.listen(PORT,'127.0.0.1',r));
const browser=await puppeteer.launch({executablePath:'/usr/local/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-gpu']});
const page=await browser.newPage(); await page.setViewport({width:1280,height:900});
await page.goto(`http://127.0.0.1:${PORT}/#/torrents`,{waitUntil:'load'});
await new Promise(r=>setTimeout(r,900));
await page.screenshot({path:join(OUT,'27-torrents.png')});
console.log('shot torrents');
await page.goto(`http://127.0.0.1:${PORT}/#/developers`,{waitUntil:'load'});
await new Promise(r=>setTimeout(r,900));
await page.screenshot({path:join(OUT,'28-developers.png'), fullPage:false});
console.log('shot developers');
const mobile=await browser.newPage(); await mobile.setViewport({width:390,height:844,deviceScaleFactor:2});
await mobile.goto(`http://127.0.0.1:${PORT}/#/developers`,{waitUntil:'load'});
await new Promise(r=>setTimeout(r,900));
await mobile.screenshot({path:join(OUT,'29-developers-mobile.png')});
console.log('shot developers mobile');
await browser.close(); server.close();
